import { moduleOf } from './analysisPlan';
import type { BrainMap, MapEntry } from './brain';

// The brain's index note: a generated map between auto markers, kept apart from the user's own notes.

const AUTO_START = '<!-- my_editor:auto — regenerated by "Build Project Brain"; edit outside these markers -->';
const AUTO_END = '<!-- /my_editor:auto -->';
const INDEX_BUDGET_CHARS = 7_000;
const LANGUAGE_NAMES: Record<string, string> = {
	ts: 'TypeScript', js: 'JavaScript', py: 'Python', rs: 'Rust', go: 'Go', c: 'C/C++', other: 'other',
};

/** The index's one-line description until the user (or Analyse) replaces it. */
export const PLACEHOLDER = 'One line on what this project is and who it is for — edit me.';

/**
 * The best one-line description of a file: the user's note, then the pair's summary of the whole file, then the
 * leading doc comment (which often describes only the first declaration).
 */
export function describeEntry(entry: MapEntry | undefined): string {
	return entry?.note ?? entry?.summary ?? entry?.role ?? (entry?.exports.length ? `exports ${entry.exports.slice(0, 4).join(', ')}` : '');
}

/** Replaces only the text between the markers, so the user's own notes survive every rebuild. */
export function mergeAuto(existing: string | undefined, auto: string, head: string, tail = '\n'): string {
	const block = `${AUTO_START}\n${auto}\n${AUTO_END}`;
	if (!existing) {
		return `${head}${block}${tail}`;
	}
	const start = existing.indexOf(AUTO_START);
	const end = existing.indexOf(AUTO_END);
	if (start >= 0 && end > start) {
		return existing.slice(0, start) + block + existing.slice(end + AUTO_END.length);
	}
	return `${existing.trimEnd()}\n\n${block}\n`;
}

/** The index note: when new, a title and the placeholder line, then the generated map, then a Notes section for the user. */
export function indexNote(existing: string | undefined, auto: string, projectName: string): string {
	return mergeAuto(existing, auto, `# ${projectName}\n\n${PLACEHOLDER}\n\n`,
		'\n\n## Notes\n\nDecisions, gotchas and anything the pair should always know.\n');
}

/** A short, bounded map of the project: stack, modules, and (for small projects) every file's role. */
export function mapSection(map: BrainMap, maxFiles: number): string {
	const entries = Object.entries(map.files);
	const byLanguage = new Map<string, number>();
	const byModule = new Map<string, string[]>();
	for (const [path, entry] of entries) {
		byLanguage.set(entry.language, (byLanguage.get(entry.language) ?? 0) + 1);
		const module = moduleOf(path);
		byModule.set(module, [...(byModule.get(module) ?? []), path]);
	}
	const languages = [...byLanguage].map(([language, count]) => `${LANGUAGE_NAMES[language]} ${count}`).join(', ');
	const mostUsed = entries.sort((a, b) => b[1].importedBy.length - a[1].importedBy.length).slice(0, 5)
		.filter(([, e]) => e.importedBy.length).map(([p, e]) => `\`${p}\` (${e.importedBy.length})`).join(', ');
	const lines = [
		`## Map`,
		'',
		`- **Files:** ${entries.length} (${languages})${map.commit ? ` · built at ${map.commit}` : ''}`,
		`- **Most used:** ${mostUsed || 'none yet'}`,
		'',
		'## Modules',
		'',
	];
	const small = entries.length <= 60;
	for (const [module, paths] of [...byModule].sort()) {
		const about = map.modules?.[module];
		lines.push(`- \`${module}\` — ${paths.length} file${paths.length === 1 ? '' : 's'}${about ? `. ${about}` : ''}`);
		if (small) {
			for (const path of paths.sort()) {
				const what = describeEntry(map.files[path]);
				lines.push(`  - \`${path}\`${what ? ` — ${what}` : ''}`);
			}
		}
	}
	const gaps = coverageGaps(map, maxFiles, entries.filter(([, e]) => !e.summary && !e.note && !e.role).length);
	if (gaps.length) {
		lines.splice(4, 0, `- **Not covered:** ${gaps.join('; ')}`);
	}
	let text = lines.join('\n');
	if (text.length > INDEX_BUDGET_CHARS) {
		text = `${text.slice(0, INDEX_BUDGET_CHARS)}\n- … (trimmed to keep the brain short; see map.json)`;
	}
	return text;
}

/** What the map leaves out: files past the limit, files too large to read, files without a summary yet. */
function coverageGaps(map: BrainMap, maxFiles: number, unsummarised: number): string[] {
	const tooLarge = map.tooLarge ?? [];
	return [
		map.fileLimitHit ? `only the first ${maxFiles} code files are mapped` : '',
		tooLarge.length
			? `${tooLarge.length} file${tooLarge.length === 1 ? ' is' : 's are'} too large to read `
				+ `(${tooLarge.slice(0, 3).join(', ')}${tooLarge.length > 3 ? ', …' : ''})`
			: '',
		map.modules && unsummarised ? `${unsummarised} file${unsummarised === 1 ? ' has' : 's have'} no summary yet` : '',
	].filter(Boolean);
}
